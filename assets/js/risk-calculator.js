function buildPayTable(volNum){
  const tables={
    1:[[0,55],[0.5,20],[1,12],[1.5,7],[2,4],[3,1.5],[5,0.5]],
    2:[[0,58],[0.5,16],[1,12],[2,7],[3,4],[5,2],[10,0.8],[20,0.2]],
    3:[[0,62],[1,12],[2,8],[5,6],[10,4],[20,2],[50,0.8],[100,0.2]],
    4:[[0,68],[1,10],[2,7],[5,6],[10,4],[25,3],[50,1.5],[100,0.4],[200,0.1]],
    5:[[0,74],[1,8],[2,5],[5,5],[10,4],[25,2],[75,1],[200,0.5],[500,0.1],[1000,0.05]]
  };
  const raw=tables[volNum]||tables[3];
  const tot=raw.reduce((s,e)=>s+e[1],0);
  let cum=0;
  return raw.map(([mult,w])=>{cum+=w/tot;return{mult,cumProb:cum};});
}
function calcEV(pt){
  let ev=0,prev=0;
  pt.forEach(e=>{ev+=e.mult*(e.cumProb-prev);prev=e.cumProb;});
  return ev;
}
function spinSlot(pt,bet,scale){
  const r=Math.random();
  const e=pt.find(x=>r<=x.cumProb)||pt[pt.length-1];
  return bet*e.mult*scale;
}

function monteCarloSlot({bankroll,bet,spins,rtp,volNum,simulations}){
  const pt=buildPayTable(volNum),evRaw=calcEV(pt),scale=evRaw>0?rtp/evRaw:1;
  let ruinCount=0,totalFinal=0;
  for(let i=0;i<simulations;i++){
    let b=bankroll,ruined=false;
    for(let s=0;s<spins;s++){
      if(b<bet){ruinCount++;ruined=true;break;}
      b=b-bet+spinSlot(pt,bet,scale);
    }
    totalFinal+=ruined?0:Math.max(b,0);
  }
  return{ruinProbability:ruinCount/simulations,avgFinalBankroll:totalFinal/simulations,houseEdge:1-rtp};
}

// ═══════════════════════════════════════════════════════
// MONTE CARLO — ROULETTE (esatto per definizione)
// ═══════════════════════════════════════════════════════
function monteCarloRoulette({bankroll,bet,rounds,simulations,winProb,payout,laPartageActive,zeros,total}){
  let ruinCount=0,totalFinal=0;
  const zeroProb=zeros/total;
  for(let i=0;i<simulations;i++){
    let b=bankroll,ruined=false;
    for(let s=0;s<rounds;s++){
      if(b<bet){ruinCount++;ruined=true;break;}
      const r=Math.random();
      if(r<winProb){
        b+=bet*(payout-1); // vinci: ricevi payout netto
      } else if(laPartageActive && r<winProb+zeroProb){
        b-=bet*0.5; // zero con La Partage: perdi metà
      } else {
        b-=bet; // perdi tutto
      }
    }
    totalFinal+=ruined?0:Math.max(b,0);
  }
  return{ruinProbability:ruinCount/simulations,avgFinalBankroll:totalFinal/simulations};
}

// ═══════════════════════════════════════════════════════
// MONTE CARLO — BLACKJACK (modello semplificato realistico)
// Il BJ ha una distribuzione degli esiti per mano basata su
// probabilità empiriche con strategia base:
//   - Vittoria normale (~43.5%): +1× la puntata
//   - Blackjack naturale (~4.8%): +1.5× la puntata
//   - Pareggio/Push (~8.5%): 0
//   - Sconfitta (~43.2%): -1× la puntata
// I valori cambiano leggermente per variante (edge diverso)
// ═══════════════════════════════════════════════════════
function monteCarloBJ({bankroll,bet,hands,simulations,bjVariant}){
  const v=BJ_VARIANTS[bjVariant];
  // Distribuzione empirica: [outcome_netto, probabilità_cumulativa]
  // calibrata per rispettare l'edge dichiarato della variante
  // Base: Classic (edge 0.58%)
  // Adattiamo le prob di win/loss per matchare l'edge
  const edge=v.edge;
  // win_prob + bj_prob - loss_prob = -edge  (profitto atteso negativo)
  // usiamo valori empirici e scaliamo la prob di vittoria
  const bjProb    = 0.0475;  // ~4.75% blackjack naturale
  const pushProb  = 0.0850;  // ~8.5%  pareggio
  // win e loss si bilanciano attorno all'edge
  // EV = winP*1 + bjP*1.5 + pushP*0 - lossP*1 = -edge
  // winP + lossP = 1 - bjP - pushP = rimanente
  const remaining = 1 - bjProb - pushProb;
  // winP - lossP = -edge - bjP*0.5   (dal calcolo EV)
  const diff      = -edge - bjProb*0.5;
  const winProb   = (remaining + diff) / 2;
  const lossProb  = remaining - winProb;

  // Cumulative
  const cum = [
    { net: 1.5, cp: bjProb },
    { net: 1,   cp: bjProb+winProb },
    { net: 0,   cp: bjProb+winProb+pushProb },
    { net:-1,   cp: 1.0 }
  ];

  let ruinCount=0,totalFinal=0;
  for(let i=0;i<simulations;i++){
    let b=bankroll,ruined=false;
    for(let s=0;s<hands;s++){
      if(b<bet){ruinCount++;ruined=true;break;}
      const r=Math.random();
      const outcome=cum.find(x=>r<=x.cp)||cum[cum.length-1];
      b+=bet*outcome.net;
    }
    totalFinal+=ruined?0:Math.max(b,0);
  }
  return{ruinProbability:ruinCount/simulations,avgFinalBankroll:totalFinal/simulations,houseEdge:v.edge};
}

